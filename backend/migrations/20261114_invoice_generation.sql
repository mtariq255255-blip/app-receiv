
-- ============================================================
-- RECEIVAI UAE
-- INVOICE GENERATION MODULE - DATABASE MIGRATION v1.0
-- Compatible with PostgreSQL (Neon / AWS RDS)
--
-- Creates:
--   1. invoice_drafts
--   2. invoice_draft_items
--   3. generated_invoice_documents
--   4. Unique invoice-number sequence
--
-- Does NOT modify existing invoices, invoice_items,
-- invoice_documents, payments, or reminders.
-- ============================================================

BEGIN;

-- ============================================================
-- 1. INVOICE NUMBER SEQUENCE
-- ============================================================

-- Used by the invoice number service.
-- Example: RAI-GEN-2026-000001
-- Final invoice numbers must also satisfy the existing
-- invoices.invoice_number UNIQUE constraint.

CREATE SEQUENCE IF NOT EXISTS receivai_generated_invoice_number_seq
    AS BIGINT
    INCREMENT BY 1
    MINVALUE 1
    START WITH 1
    CACHE 1;


-- ============================================================
-- 2. INVOICE DRAFTS
-- ============================================================

-- Stores invoice data before finalization.
--
-- form_data contains the non-item fields:
-- seller, buyer, invoice header, wordmark settings,
-- custom columns, custom fields, bank details,
-- notes, declaration and footer.
--
-- Line items are stored separately in invoice_draft_items.
--
-- Drafts do not appear in the existing invoice register.

CREATE TABLE IF NOT EXISTS invoice_drafts (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    created_by_id BIGINT NOT NULL
        REFERENCES admin_users(id)
        ON DELETE RESTRICT,

    updated_by_id BIGINT
        REFERENCES admin_users(id)
        ON DELETE SET NULL,

    draft_title VARCHAR(120),

    status VARCHAR(20)
        NOT NULL DEFAULT 'draft',

    version INTEGER
        NOT NULL DEFAULT 1,

    form_data JSONB
        NOT NULL DEFAULT '{}'::jsonb,

    finalized_invoice_id BIGINT UNIQUE
        REFERENCES invoices(id)
        ON DELETE RESTRICT,

    finalization_key VARCHAR(128) UNIQUE,

    created_at TIMESTAMPTZ
        NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ
        NOT NULL DEFAULT NOW(),

    CONSTRAINT ck_invoice_drafts_status
        CHECK (
            status IN (
                'draft',
                'finalized',
                'cancelled'
            )
        ),

    CONSTRAINT ck_invoice_drafts_version
        CHECK (version >= 1),

    CONSTRAINT ck_invoice_drafts_form_data
        CHECK (
            jsonb_typeof(form_data) = 'object'
        ),

    CONSTRAINT ck_invoice_drafts_finalization
        CHECK (
            (
                status = 'finalized'
                AND finalized_invoice_id IS NOT NULL
                AND finalization_key IS NOT NULL
            )
            OR
            (
                status IN ('draft', 'cancelled')
                AND finalized_invoice_id IS NULL
            )
        )
);


-- ============================================================
-- 3. INVOICE DRAFT LINE ITEMS
-- ============================================================

-- Stores editable line items.
--
-- Supports:
--   - Product/service description
--   - Quantity
--   - Unit
--   - Unit price
--   - Discount
--   - VAT rate
--   - Custom line-item columns
--   - Custom line-item fields
--   - Row ordering
--
-- Incomplete values are allowed for drafts.
-- Financial validation is required before finalization.

CREATE TABLE IF NOT EXISTS invoice_draft_items (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    draft_id BIGINT NOT NULL
        REFERENCES invoice_drafts(id)
        ON DELETE CASCADE,

    client_id VARCHAR(80),

    description VARCHAR(500),

    quantity NUMERIC(14, 3),

    unit VARCHAR(40),

    unit_price_aed NUMERIC(14, 2),

    discount_aed NUMERIC(14, 2)
        NOT NULL DEFAULT 0.00,

    vat_rate NUMERIC(5, 2),

    sort_order INTEGER
        NOT NULL DEFAULT 0,

    custom_values JSONB
        NOT NULL DEFAULT '{}'::jsonb,

    custom_fields JSONB
        NOT NULL DEFAULT '[]'::jsonb,

    created_at TIMESTAMPTZ
        NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ
        NOT NULL DEFAULT NOW(),

    CONSTRAINT ck_invoice_draft_items_quantity
        CHECK (
            quantity IS NULL OR quantity > 0
        ),

    CONSTRAINT ck_invoice_draft_items_unit_price
        CHECK (
            unit_price_aed IS NULL
            OR unit_price_aed >= 0
        ),

    CONSTRAINT ck_invoice_draft_items_discount
        CHECK (
            discount_aed >= 0
        ),

    CONSTRAINT ck_invoice_draft_items_vat_rate
        CHECK (
            vat_rate IS NULL
            OR (
                vat_rate >= 0
                AND vat_rate <= 100
            )
        ),

    CONSTRAINT ck_invoice_draft_items_sort_order
        CHECK (
            sort_order >= 0
        ),

    CONSTRAINT ck_invoice_draft_items_custom_values
        CHECK (
            jsonb_typeof(custom_values) = 'object'
        ),

    CONSTRAINT ck_invoice_draft_items_custom_fields
        CHECK (
            jsonb_typeof(custom_fields) = 'array'
        )
);


-- ============================================================
-- 4. GENERATED INVOICE DOCUMENTS
-- ============================================================

-- Stores metadata for finalized invoice PDFs.
--
-- The PDF is stored in private application storage.
-- The database stores its path, filename and checksum.
--
-- invoice_snapshot retains all original generation data,
-- including:
--   - Seller and buyer details
--   - Invoice information
--   - All line items
--   - Custom fields
--   - Company text-wordmark settings
--   - Bank details
--   - Notes and declarations
--   - Final calculated financial totals
--
-- This preserves invoice presentation details even when
-- they are not fields in the existing accounting tables.

CREATE TABLE IF NOT EXISTS generated_invoice_documents (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    invoice_id BIGINT NOT NULL UNIQUE
        REFERENCES invoices(id)
        ON DELETE RESTRICT,

    draft_id BIGINT NOT NULL UNIQUE
        REFERENCES invoice_drafts(id)
        ON DELETE RESTRICT,

    created_by_id BIGINT NOT NULL
        REFERENCES admin_users(id)
        ON DELETE RESTRICT,

    pdf_filename VARCHAR(255) NOT NULL,

    pdf_storage_path TEXT NOT NULL,

    pdf_mime_type VARCHAR(100)
        NOT NULL DEFAULT 'application/pdf',

    pdf_size_bytes BIGINT NOT NULL,

    pdf_sha256 VARCHAR(64) NOT NULL,

    template_version VARCHAR(30)
        NOT NULL DEFAULT 'v1',

    invoice_snapshot JSONB NOT NULL,

    generated_at TIMESTAMPTZ
        NOT NULL DEFAULT NOW(),

    CONSTRAINT ck_generated_invoice_documents_pdf_name
        CHECK (
            length(btrim(pdf_filename)) > 0
        ),

    CONSTRAINT ck_generated_invoice_documents_pdf_path
        CHECK (
            length(btrim(pdf_storage_path)) > 0
        ),

    CONSTRAINT ck_generated_invoice_documents_pdf_mime
        CHECK (
            pdf_mime_type = 'application/pdf'
        ),

    CONSTRAINT ck_generated_invoice_documents_pdf_size
        CHECK (
            pdf_size_bytes > 0
        ),

    CONSTRAINT ck_generated_invoice_documents_pdf_sha256
        CHECK (
            pdf_sha256 ~ '^[a-fA-F0-9]{64}$'
        ),

    CONSTRAINT ck_generated_invoice_documents_snapshot
        CHECK (
            jsonb_typeof(invoice_snapshot) = 'object'
        )
);


-- ============================================================
-- 5. DATABASE INDEXES
-- ============================================================

-- Quickly retrieve drafts created by an administrator.

CREATE INDEX IF NOT EXISTS ix_invoice_drafts_created_by_updated
    ON invoice_drafts (
        created_by_id,
        updated_at DESC
    );


-- Quickly retrieve drafts by status.

CREATE INDEX IF NOT EXISTS ix_invoice_drafts_status_updated
    ON invoice_drafts (
        status,
        updated_at DESC
    );


-- Retrieve invoice draft items in their correct order.

CREATE INDEX IF NOT EXISTS ix_invoice_draft_items_draft_order
    ON invoice_draft_items (
        draft_id,
        sort_order,
        id
    );


-- ============================================================
-- 6. COMPLETE MIGRATION
-- ============================================================

COMMIT;
